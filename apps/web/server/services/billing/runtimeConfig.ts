export async function getBillingRuntimeSettingsAdmin() {
  const rows = await readRuntimeRows();
  const result: Record<string, any> = {};
  (Object.keys(DEFAULTS) as RuntimeKey[]).forEach((key) => {
    const row = rows.get(key);
    const value = decodeValue(key, row);
    const fallback = DEFAULTS[key];
    result[key] = SENSITIVE_KEYS.has(key) ? "" : value || fallback;
    result[`${key}Configured`] = Boolean(value);
    result[`${key}Masked`] = SENSITIVE_KEYS.has(key) ? maskValue(value) : value || fallback;
  });
  return result;
}

export async function updateBillingRuntimeSettings(input: Partial<Record<RuntimeKey, string | boolean | null | undefined>>, actorUserId: number) {
  const db = getDb();
  const rows = await readRuntimeRows();

  for (const key of Object.keys(DEFAULTS) as RuntimeKey[]) {
    const provided = input[key];
    if (provided === undefined) continue;
    const normalized = typeof DEFAULTS[key] === "boolean"
      ? String(Boolean(provided))
      : String(provided ?? "").trim();
    if (!normalized && SENSITIVE_KEYS.has(key)) {
      continue;
    }
    const existing = rows.get(key);
    const storedValue = SENSITIVE_KEYS.has(key) ? encrypt(normalized) : normalized;
    if (existing) {
      await db.update(systemSettings).set({
        value: storedValue,
        isSensitive: SENSITIVE_KEYS.has(key),
        updatedBy: actorUserId,
        updatedAt: new Date(),
        description: `Billing runtime setting ${key}`,
      }).where(eq(systemSettings.id, existing.id));
    } else {
      await db.insert(systemSettings).values({
        category: CATEGORY,
        key,
        value: storedValue,
        isSensitive: SENSITIVE_KEYS.has(key),
        updatedBy: actorUserId,
        description: `Billing runtime setting ${key}`,
      });
    }
  }

  return getBillingRuntimeSettingsAdmin();
}
