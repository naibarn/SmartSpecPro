type RuntimeKey = keyof typeof DEFAULTS;

function coerceBoolean(value: string | null | undefined, fallback: boolean) {
  if (value == null || value === "") return fallback;
  return value === "true";
}

function coerceString(value: string | null | undefined, fallback: string) {
  if (value == null || value === "") return fallback;
  return value;
}

function maskValue(value: string) {
  return value ? "*".repeat(Math.max(8, Math.min(24, value.length))) : "";
}

async function readRuntimeRows() {
  try {
    const db = getDb();
    const rows = await db.select().from(systemSettings).where(eq(systemSettings.category, CATEGORY));
    if (!Array.isArray(rows)) {
      return new Map();
    }
    return new Map(rows.map((row) => [row.key, row]));
  } catch {
    return new Map();
  }
}

function decodeValue(key: string, row?: { value: string | null; isSensitive: boolean | null }) {
  if (!row?.value) return "";
  return row.isSensitive ? (decrypt(row.value) || "") : row.value;
}

