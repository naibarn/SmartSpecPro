export async function listInvoiceWebhookEventsForAdmin(params: {
  tenantId: string | null;
  invoiceId: number;
  limit?: number;
}) {
  const db = getDb();
  const limit = Math.min(Math.max(params.limit ?? 100, 1), 200);
  const invoiceWhereClause = params.tenantId
    ? and(eq(invoices.id, params.invoiceId), eq(invoices.tenantId, params.tenantId))
    : eq(invoices.id, params.invoiceId);

  const [invoice] = await db
    .select({ id: invoices.id })
    .from(invoices)
    .where(invoiceWhereClause)
    .limit(1);

  if (!invoice) {
    return [];
  }

  const directEvents = await db
    .select()
    .from(webhookEvents)
    .where(eq(webhookEvents.invoiceId, invoice.id))
    .orderBy(desc(webhookEvents.createdAt))
    .limit(limit);

  if (directEvents.length > 0) {
    return directEvents
      .map((event) => ({
        ...event,
        payloadJson: sanitizeSensitiveJson(event.payloadJson),
      }));
  }

  const relatedPayments = await db
    .select({
      providerPaymentId: payments.providerPaymentId,
      providerReferenceId: payments.providerReferenceId,
      providerEventLastSeenId: payments.providerEventLastSeenId,
    })
    .from(payments)
    .where(eq(payments.invoiceId, invoice.id));

  const needles = new Set<string>();
  for (const payment of relatedPayments) {
    if (payment.providerPaymentId) needles.add(payment.providerPaymentId);
    if (payment.providerReferenceId) needles.add(payment.providerReferenceId);
    if (payment.providerEventLastSeenId) needles.add(payment.providerEventLastSeenId);
  }

  const recentEvents = await db
    .select()
    .from(webhookEvents)
    .orderBy(desc(webhookEvents.createdAt))
    .limit(Math.max(limit * 3, 120));

  return recentEvents
    .filter((event) => {
      if (needles.size === 0) {
        return false;
      }
      const haystack = JSON.stringify(event.payloadJson ?? {});
      for (const needle of needles) {
        if (haystack.includes(needle)) {
          return true;
        }
      }
      return false;
    })
    .slice(0, limit)
    .map((event) => ({
      ...event,
      payloadJson: sanitizeSensitiveJson(event.payloadJson),
    }));
}
