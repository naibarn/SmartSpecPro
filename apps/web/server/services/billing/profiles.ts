function normalizeNullableString(value: string | null | undefined): string | null {
  if (value == null) return null;
  const trimmed = value.trim();
  return trimmed ? trimmed : null;
}

function extractSqlRows(result: unknown): Array<Record<string, any>> {
  if (Array.isArray(result)) {
    return result as Array<Record<string, any>>;
  }
  if (
    result
    && typeof result === "object"
    && Array.isArray((result as { rows?: unknown }).rows)
  ) {
    return (result as { rows: Array<Record<string, any>> }).rows;
  }
  return [];
}

function sanitizeSensitiveJson(value: unknown): unknown {
  if (Array.isArray(value)) {
    return value.map(sanitizeSensitiveJson);
  }

  if (!value || typeof value !== "object") {
    return value;
  }

  const entries = Object.entries(value as Record<string, unknown>).map(([key, nestedValue]) => {
    const lowered = key.toLowerCase();
    if (
      lowered.includes("secret")
      || lowered.includes("signature")
      || lowered.includes("token")
      || lowered.includes("authorization")
      || lowered.includes("api_key")
      || lowered.includes("apikey")
      || lowered === "taxid"
      || lowered === "tax_id"
      || lowered.includes("email")
      || lowered.includes("phone")
      || lowered.includes("address")
      || lowered.includes("postal")
      || lowered.includes("district")
      || lowered.includes("province")
      || lowered.includes("country")
      || lowered.includes("contact")
      || lowered.includes("legalname")
      || lowered.includes("entityname")
      || lowered.includes("signername")
    ) {
      return [key, "[redacted]"];
    }

    return [key, sanitizeSensitiveJson(nestedValue)];
  });

  return Object.fromEntries(entries);
}

function buildFieldDiff(previousValue: Record<string, any> | null, nextValue: Record<string, any> | null) {
  const previous = previousValue ?? {};
  const next = nextValue ?? {};
  const keys = new Set([...Object.keys(previous), ...Object.keys(next)]);
  const diff: Record<string, { before: unknown; after: unknown }> = {};
  for (const key of keys) {
    const before = previous[key];
    const after = next[key];
    if (JSON.stringify(before) !== JSON.stringify(after)) {
      diff[key] = { before, after };
    }
  }
  return diff;
}

async function billingProfilesHasTenantColumn() {
  if (billingProfilesTenantColumnCache != null) {
    return billingProfilesTenantColumnCache;
  }

  try {
    const db = getDb();
    const result = await db.execute(sql`
      select 1
      from information_schema.columns
      where table_schema = 'public'
        and table_name = 'billing_profiles'
        and column_name = 'tenantId'
      limit 1
    `);
    billingProfilesTenantColumnCache = extractSqlRows(result).length > 0;
  } catch {
    billingProfilesTenantColumnCache = false;
  }

  return billingProfilesTenantColumnCache;
}

