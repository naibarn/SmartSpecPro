async function seed() {
  console.log("Seeding Vertical Drama Series genre presets...\n");

  const sql = postgres(DATABASE_URL);

  try {
    const tableExists = await sql`
      SELECT EXISTS (
        SELECT FROM information_schema.tables
        WHERE table_name = 'vertical_drama_genre_presets'
      )
    `;

    if (!tableExists[0].exists) {
      console.log("ERROR: vertical_drama_genre_presets table does not exist. Run the migration first.");
      await sql.end();
      return;
    }

    const deleted = await sql`DELETE FROM vertical_drama_genre_presets RETURNING id`;
    console.log(`Cleared ${deleted.length} existing preset(s)\n`);

    let sortOrder = 0;
    for (const preset of GENRE_PRESETS) {
      await sql`
        INSERT INTO vertical_drama_genre_presets (
          title, category, locale, logline, "mainPlot", "seasonArc",
          tone, "cliffhangerStyle", "charactersJson", "visualBible", "sortOrder"
        ) VALUES (
          ${preset.title},
          ${preset.category},
          'th',
          ${preset.logline},
          ${preset.mainPlot},
          ${preset.seasonArc},
          ${preset.tone},
          ${preset.cliffhangerStyle},
          ${JSON.stringify(preset.characters)},
          ${preset.visualBible},
          ${sortOrder}
        )
      `;
      console.log(`  + ${preset.title} (${preset.category})`);
      sortOrder += 1;
    }

    console.log(`\nSeeded ${GENRE_PRESETS.length} genre presets.\n`);
  } catch (error) {
    console.error("Error seeding genre presets:", error);
    throw error;
  } finally {
    await sql.end();
  }
}

