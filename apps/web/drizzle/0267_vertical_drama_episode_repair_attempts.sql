CREATE TABLE IF NOT EXISTS "vertical_drama_episode_repair_attempts" (
  "id" bigserial PRIMARY KEY NOT NULL,
  "tenantId" varchar(36) NOT NULL,
  "userId" integer NOT NULL REFERENCES "users"("id") ON DELETE cascade,
  "seriesId" bigint NOT NULL REFERENCES "vertical_drama_series"("id") ON DELETE cascade,
  "episodeId" bigint NOT NULL REFERENCES "vertical_drama_episodes"("id") ON DELETE cascade,
  "revisionId" bigint NOT NULL REFERENCES "vertical_drama_episode_revisions"("id") ON DELETE cascade,
  "jobId" varchar(64),
  "attemptNumber" integer NOT NULL,
  "stage" varchar(32) NOT NULL,
  "skillSlug" varchar(160) NOT NULL,
  "planningAttemptNumber" integer NOT NULL,
  "model" varchar(255),
  "providerId" integer,
  "providerName" varchar(120),
  "providerCallId" varchar(64),
  "outcome" varchar(32) NOT NULL,
  "rawOutput" text,
  "rawOutputHash" varchar(64),
  "rawOutputTruncated" boolean NOT NULL DEFAULT false,
  "parsedOutput" jsonb,
  "responseMetadata" jsonb,
  "physicalAttempts" jsonb,
  "promptHash" varchar(64),
  "systemPromptLength" integer,
  "userPromptLength" integer,
  "inputTokens" integer,
  "outputTokens" integer,
  "finishReason" varchar(80),
  "errorCode" varchar(100),
  "errorMessage" text,
  "safetyFindings" jsonb,
  "schemaIssues" jsonb,
  "startedAt" timestamptz,
  "completedAt" timestamptz,
  "createdAt" timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS "vds_episode_repair_attempt_lookup_idx" ON "vertical_drama_episode_repair_attempts" ("tenantId", "userId", "episodeId", "revisionId", "createdAt");
CREATE INDEX IF NOT EXISTS "vds_episode_repair_attempt_job_idx" ON "vertical_drama_episode_repair_attempts" ("tenantId", "jobId", "createdAt");
